/** Deterministic, offline legal copy source -> bundled immutable TS string constants.
 * Actual public content should still be imported and approved through versioned CMS.
 * Never publishes, writes to DB, or makes network calls. --check verifies parity.
 */
import {readFileSync,writeFileSync,existsSync} from 'node:fs'
import {resolve} from 'node:path'
import {createHash} from 'node:crypto'
const root=resolve(import.meta.dirname,'..')
const keys=['privacy','terms','messaging-terms','messaging-privacy']
const content=Object.fromEntries(keys.map(k=>[k,readFileSync(resolve(root,'content/legal',`${k}.txt`),'utf8').trimEnd()+'\n']))
const hash=createHash('sha256').update(JSON.stringify(content)).digest('hex')
const payload=`/* GENERATED BY scripts/generate-policy-static.mjs — DO NOT EDIT DIRECTLY.\n * Source: content/legal/*.txt. Draft copy pending counsel and owner release approval.\n * SHA256: ${hash}\n */\nexport const OWNER_LEGAL_COPY: Readonly<Record<'privacy'|'terms'|'messaging-terms'|'messaging-privacy',string>> = ${JSON.stringify(content,null,2)}\nexport const OWNER_LEGAL_COPY_SHA256 = '${hash}'\n`
const out=resolve(root,'lib/owner-legal-generated.ts')
if(process.argv.includes('--check')){
 if(!existsSync(out)||readFileSync(out,'utf8')!==payload){console.error('Owner legal copy and generated policy snapshot differ. Run npm run legal:generate.');process.exitCode=1}
 else console.log('PASS October 6 policy sources match compiled snapshot (4 documents)')
}else{
 writeFileSync(out,payload);console.log('Generated legal snapshot from 4 source documents; no publication')
}
